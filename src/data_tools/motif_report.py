"""Generate `reports/pharmacophore_features.md` from the motif table.

The report is generated from the same objects that produce the features, so the
published documentation and the computed columns cannot drift. A motif or
descriptor without a literature source raises: that is the mechanism enforcing
RULES.md section 5 (do not encode chemistry from memory or on an AI tool's word).
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import polars as pl

import representations.cyp_pharmacophore as cp

_DEFAULT_OUT = Path("reports/pharmacophore_features.md")


def uncited_entries() -> list[str]:
    """Return the names of every motif and descriptor lacking a source."""
    missing = [m.name for m in cp._MOTIFS if not m.source.strip()]
    missing += [d.name for d in cp._ISOFORM_FEATURES if not d.source.strip()]
    return missing


def _prevalence(block, df: pl.DataFrame) -> dict[str, float]:
    """Percent of PARSEABLE molecules with a non-zero value, per column.

    Invalid SMILES are all-NaN rows; counting them as absent would understate
    prevalence rather than report it on the molecules actually measured.
    """
    arr = block.transform(df["SMILES"])
    names = block.feature_names
    if arr.shape[0] == 0:
        return {n: 0.0 for n in names}
    valid = ~np.isnan(arr).all(axis=1)
    n_valid = int(valid.sum())
    if n_valid == 0:
        return {n: 0.0 for n in names}
    present = (arr[valid] > 0).sum(axis=0)
    return {n: 100.0 * float(c) / n_valid for n, c in zip(names, present)}


def build_report(train_df: pl.DataFrame, test_df: pl.DataFrame) -> str:
    """Return the full markdown report, or raise if anything is uncited."""
    missing = uncited_entries()
    if missing:
        raise ValueError(
            f"{len(missing)} uncited entr{'y' if len(missing) == 1 else 'ies'}: "
            f"{', '.join(missing)}. Every motif and descriptor needs a literature "
            "source before the report or any benchmark runs (RULES.md section 5)."
        )

    blocks = [
        ("Heme-coordination motifs", cp.HemeCoordinationMotifs(), "heme"),
        ("Mechanism-based inactivation alerts", cp.MechanismBasedAlerts(), "tdi"),
    ]

    lines = [
        "# CYP pharmacophore features",
        "",
        "Generated by `motif-report` from `src/representations/cyp_pharmacophore.py`.",
        "Do not edit by hand — edit the motif table and regenerate.",
        "",
        f"Motif table version: `{cp.TABLE_VERSION}`",
        "",
        "Prevalence is the percent of **parseable** molecules with a non-zero value.",
        "",
    ]

    for title, block, block_tag in blocks:
        train_prev = _prevalence(block, train_df)
        test_prev = _prevalence(block, test_df)
        lines += [
            f"## {title}",
            "",
            "| Feature | SMARTS | T6 rollup | Train % | Test % | Source |",
            "|---|---|---|---|---|---|",
        ]
        for m in (x for x in cp._MOTIFS if x.block == block_tag):
            lines.append(
                f"| `{m.name}` | `{m.smarts}` | {m.rollup or '—'} | "
                f"{train_prev[m.name]:.1f} | {test_prev[m.name]:.1f} | {m.source} |"
            )
        lines.append("")
        notes = [(x.name, x.note) for x in cp._MOTIFS if x.block == block_tag and x.note]
        if notes:
            lines.append("**Notes**")
            lines.append("")
            lines += [f"- `{n}` — {note}" for n, note in notes]
            lines.append("")

    iso = cp.IsoformPreferenceDescriptors()
    lines += [
        "## Isoform-preference descriptors",
        "",
        "| Feature | Source | Note |",
        "|---|---|---|",
    ]
    for d in cp._ISOFORM_FEATURES:
        lines.append(f"| `{d.name}` | {d.source} | {d.note or '—'} |")
    lines += ["", f"Registered as `{iso.name}`.", ""]

    erg = cp.ErGFingerprint()
    lines += [
        "## Generic comparator",
        "",
        f"`{erg.name}` — RDKit ErG fingerprint, {cp.ERG_N_FEATURES} features at "
        "library defaults. If the hand-written motifs above do not beat this, "
        "they are not worth maintaining.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the pharmacophore motif report.")
    parser.add_argument("--train", default="data/union_train.csv")
    parser.add_argument("--test", default="data/test.csv")
    parser.add_argument("--out", default=str(_DEFAULT_OUT))
    args = parser.parse_args()

    train_df = pl.read_csv(args.train)
    test_df = pl.read_csv(args.test)
    text = build_report(train_df, test_df)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({len(text.splitlines())} lines)")
